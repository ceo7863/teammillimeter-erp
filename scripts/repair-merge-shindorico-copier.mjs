#!/usr/bin/env node
/**
 * Merge 신도리코중앙 + 복합기사용료 into one fixed expense (복합기사용료).
 *
 * Usage:
 *   npx tsx scripts/repair-merge-shindorico-copier.mjs [dbPath] [--dry-run]
 */
import { DatabaseSync } from "node:sqlite";
import {
  isFixedExpensePaymentBankLinked,
  pruneSettledDuplicateFixedExpensePayments,
} from "../src/utils/companyLedger.ts";

const KEEP_ID = "0720dd9c-6fe8-4b76-82f9-b08ed0a9a759";
const REMOVE_ID = "2a942748-5eae-4852-85c4-63d3c61696fc";

const dbPath = process.argv.find((arg) => !arg.startsWith("-") && arg.endsWith(".sqlite")) || "data/erp.sqlite";
const dryRun = process.argv.includes("--dry-run");
const AUTO_MEMO = "\uC790\uB3D9 \uB4F1\uB85D";

function monthKey(date) {
  return String(date || "").slice(0, 7);
}

function isAutoGeneratedPayment(payment) {
  return String(payment.memo || "").includes(AUTO_MEMO);
}

function chooseMonthPayment(group, bankTransactions) {
  const linked = group.filter((row) => isFixedExpensePaymentBankLinked(row, bankTransactions));
  if (linked.length === 1) {
    return { keep: linked[0], drop: group.filter((row) => row.id !== linked[0].id) };
  }
  if (linked.length > 1) {
    const manual = linked.find((row) => !isAutoGeneratedPayment(row));
    const keep = manual || linked[0];
    return { keep, drop: group.filter((row) => row.id !== keep.id) };
  }
  const manual = group.find((row) => !isAutoGeneratedPayment(row));
  if (manual) return { keep: manual, drop: group.filter((row) => row.id !== manual.id) };
  return { keep: group[0], drop: group.slice(1) };
}

const db = new DatabaseSync(dbPath);
const state = db.prepare("SELECT payload, version FROM erp_state WHERE id = 1").get();
const data = JSON.parse(String(state.payload));

const keepItem = (data.fixedExpenses || []).find((row) => row.id === KEEP_ID);
const removeItem = (data.fixedExpenses || []).find((row) => row.id === REMOVE_ID);
if (!keepItem || !removeItem) {
  console.log(JSON.stringify({ error: "fixed expense not found", keepItem: Boolean(keepItem), removeItem: Boolean(removeItem) }));
  process.exit(1);
}

let payments = [...(data.fixedExpensePayments || [])];
let bankTransactions = [...(data.bankTransactions || [])];
let bankLedgerRules = [...(data.bankLedgerRules || [])];

const duplicatePayments = payments.filter((row) => row.fixedExpenseId === REMOVE_ID);
payments = payments.filter((row) => row.fixedExpenseId !== REMOVE_ID);

const canonicalPayments = payments.filter((row) => row.fixedExpenseId === KEEP_ID);
const combined = [
  ...canonicalPayments,
  ...duplicatePayments.map((row) => ({ ...row, fixedExpenseId: KEEP_ID })),
];

const byMonth = new Map();
for (const payment of combined) {
  const mk = monthKey(payment.date);
  if (!byMonth.has(mk)) byMonth.set(mk, []);
  byMonth.get(mk).push(payment);
}

const nextCanonicalPayments = [];
const removedPaymentIds = new Set();
let reassigned = 0;

for (const group of byMonth.values()) {
  const { keep, drop } = chooseMonthPayment(group, bankTransactions);
  nextCanonicalPayments.push({ ...keep, fixedExpenseId: KEEP_ID });
  if (keep.fixedExpenseId === REMOVE_ID || duplicatePayments.some((row) => row.id === keep.id)) {
    reassigned += 1;
  }
  for (const row of drop) removedPaymentIds.add(row.id);
}

payments = [...payments.filter((row) => row.fixedExpenseId !== KEEP_ID), ...nextCanonicalPayments];

bankTransactions = bankTransactions.map((tx) => {
  if (!removedPaymentIds.has(String(tx.linkedFixedExpensePaymentId || ""))) return tx;
  return { ...tx, linkedFixedExpensePaymentId: undefined };
});

bankLedgerRules = bankLedgerRules.map((rule) => {
  if (rule.kind === "fixed" && rule.fixedExpenseId === REMOVE_ID) {
    return { ...rule, fixedExpenseId: KEEP_ID };
  }
  return rule;
});

const fixedExpenses = (data.fixedExpenses || [])
  .filter((row) => row.id !== REMOVE_ID)
  .map((row) =>
    row.id === KEEP_ID
      ? {
          ...row,
          name: "\uBCF5\uD569\uAE30\uC0AC\uC6A9\uB8CC",
          category: "\uAD6C\uB3C5/\uC11C\uBE44\uC2A4",
          amount: 88000,
          paymentDayOfMonth: row.paymentDayOfMonth || removeItem.paymentDayOfMonth || 10,
          startDate:
            [row.startDate, removeItem.startDate].filter(Boolean).sort()[0] || row.startDate || "2026-02-01",
          memo: "\uC2E0\uB3C4\uB9AC\uCF54\uC911\uC559 \u00B7 \uB098\uC774\uC2A4\uC815\uBCF4\uD1B5\uC2E0",
          isActive: true,
        }
      : row,
  );

const pruned = pruneSettledDuplicateFixedExpensePayments({
  fixedExpensePayments: payments,
  bankTransactions,
  fixedExpenses,
});

const summary = {
  dryRun,
  keep: { id: KEEP_ID, name: "\uBCF5\uD569\uAE30\uC0AC\uC6A9\uB8CC" },
  removed: { id: REMOVE_ID, name: removeItem.name },
  reassignedPayments: reassigned,
  removedDuplicatePayments: removedPaymentIds.size,
  finalPaymentCount: pruned.payments.filter((row) => row.fixedExpenseId === KEEP_ID).length,
  prunedAutoPayments: pruned.removedIds.length,
};

console.log(JSON.stringify(summary, null, 2));

if (dryRun) process.exit(0);

db.prepare("UPDATE erp_state SET payload = ?, version = ?, updated_at = ?, updated_by = ? WHERE id = 1").run(
  JSON.stringify({
    ...data,
    fixedExpenses,
    fixedExpensePayments: pruned.payments,
    bankTransactions,
    bankLedgerRules,
  }),
  Number(state.version || 0) + 1,
  new Date().toISOString(),
  "repair-merge-shindorico-copier",
);
console.log("saved version", Number(state.version || 0) + 1);
