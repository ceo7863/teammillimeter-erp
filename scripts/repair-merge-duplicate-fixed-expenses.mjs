#!/usr/bin/env node
/**
 * Merge duplicate fixed-expense master items.
 *
 * Usage:
 *   npx tsx scripts/repair-merge-duplicate-fixed-expenses.mjs [dbPath] [--dry-run]
 */
import { DatabaseSync } from "node:sqlite";
import {
  isFixedExpensePaymentBankLinked,
  pruneSettledDuplicateFixedExpensePayments,
} from "../src/utils/companyLedger.ts";

const dbPath = process.argv.find((arg) => !arg.startsWith("-") && arg.endsWith(".sqlite")) || "data/erp.sqlite";
const dryRun = process.argv.includes("--dry-run");
const HANGUL = "\uac00-\ud7a3";
const AUTO_MEMO = "\uC790\uB3D9 \uB4F1\uB85D";
const ROOM_SUFFIX = "\uD638";
const RENT_CATEGORY = "\uC784\uB300\uB8CC";

function normalizeFixedExpenseMatchKey(text) {
  return String(text || "")
    .toLowerCase()
    .replace(/\s+/g, "")
    .replace(new RegExp(`[^\\w${HANGUL}]`, "g"), "");
}

function extractFixedExpenseRoomKey(text) {
  const match = normalizeFixedExpenseMatchKey(text).match(new RegExp(`(\\d+)${ROOM_SUFFIX}`));
  return match?.[1] || "";
}

function monthKey(date) {
  return String(date || "").slice(0, 7);
}

function isAutoGeneratedPayment(payment) {
  return String(payment.memo || "").includes(AUTO_MEMO);
}

function resolveBankTransaction(payment, bankTransactions) {
  const directId = String(payment.bankTransactionId || "").trim();
  if (directId) return bankTransactions.find((tx) => tx.id === directId) || null;
  return bankTransactions.find((tx) => tx.linkedFixedExpensePaymentId === payment.id) || null;
}

function isRentLikeExpense(expense) {
  const key = normalizeFixedExpenseMatchKey(`${expense.name} ${expense.category}`);
  return expense.category === RENT_CATEGORY || key.includes(normalizeFixedExpenseMatchKey(RENT_CATEGORY));
}

function amountsCompatible(a, b) {
  return a === b || Math.abs(Number(a) - Number(b)) <= 1000;
}

function bankHaystackForExpense(expense, payments, bankTransactions) {
  const chunks = [];
  for (const payment of payments) {
    if (payment.fixedExpenseId !== expense.id) continue;
    if (!isFixedExpensePaymentBankLinked(payment, bankTransactions)) continue;
    const tx = resolveBankTransaction(payment, bankTransactions);
    if (!tx) continue;
    chunks.push(tx.description, tx.counterpartyName, tx.memo, payment.memo);
  }
  return normalizeFixedExpenseMatchKey(chunks.filter(Boolean).join(" "));
}

function bankAliasMatch(a, b, payments, bankTransactions) {
  const keyA = normalizeFixedExpenseMatchKey(a.name);
  const keyB = normalizeFixedExpenseMatchKey(b.name);
  if (keyA.length < 4 && keyB.length < 4) return false;
  if (!amountsCompatible(a.amount, b.amount)) return false;

  const hayA = bankHaystackForExpense(a, payments, bankTransactions);
  const hayB = bankHaystackForExpense(b, payments, bankTransactions);
  if (keyA.length >= 4 && hayB.includes(keyA)) return true;
  if (keyB.length >= 4 && hayA.includes(keyB)) return true;
  return false;
}

function linkedPaymentCount(expense, payments, bankTransactions) {
  return payments.filter(
    (row) =>
      row.fixedExpenseId === expense.id &&
      isFixedExpensePaymentBankLinked(row, bankTransactions),
  ).length;
}

function rentNameScore(expense) {
  let score = 0;
  if (new RegExp(`\\uC784\\uB300\\uB8CC\\(\\d+${ROOM_SUFFIX}\\)`).test(String(expense.name || ""))) score += 50;
  if (expense.category === RENT_CATEGORY) score += 30;
  return score;
}

function scoreFixedExpense(expense, payments, bankTransactions) {
  const linkedCount = linkedPaymentCount(expense, payments, bankTransactions);
  const ownCount = payments.filter((row) => row.fixedExpenseId === expense.id).length;
  let nameScore = String(expense.name || "").length;
  if (String(expense.name || "").includes("(")) nameScore += 2;
  if (/\uBCF5\uD569\uAE30|\uAD00\uB9AC\uBE44/.test(String(expense.name || ""))) nameScore += 5;
  return linkedCount * 100 + ownCount * 5 + rentNameScore(expense) + nameScore;
}

function findDuplicatePairs(fixedExpenses, payments, bankTransactions) {
  const pairs = [];
  for (let i = 0; i < fixedExpenses.length; i += 1) {
    for (let j = i + 1; j < fixedExpenses.length; j += 1) {
      const a = fixedExpenses[i];
      const b = fixedExpenses[j];
      const roomA = extractFixedExpenseRoomKey(`${a.name} ${a.category}`);
      const roomB = extractFixedExpenseRoomKey(`${b.name} ${b.category}`);
      const keyA = normalizeFixedExpenseMatchKey(a.name);
      const keyB = normalizeFixedExpenseMatchKey(b.name);

      let reason = "";
      if (roomA && roomB && roomA === roomB && amountsCompatible(a.amount, b.amount) && isRentLikeExpense(a) && isRentLikeExpense(b)) {
        reason = "room+amount+rent";
      } else if (roomA && roomB && roomA === roomB && a.category === b.category) {
        reason = "room+category";
      } else if (
        keyA.length >= 2 &&
        keyB.length >= 2 &&
        (keyA.includes(keyB) || keyB.includes(keyA)) &&
        amountsCompatible(a.amount, b.amount)
      ) {
        reason = "name+amount";
      } else if (bankAliasMatch(a, b, payments, bankTransactions)) {
        reason = "bank-alias";
      }

      if (!reason) continue;
      pairs.push({ a, b, reason });
    }
  }
  return pairs;
}

function pickCanonical(pair, payments, bankTransactions) {
  if (pair.reason === "room+amount+rent") {
    const rentA = rentNameScore(pair.a);
    const rentB = rentNameScore(pair.b);
    if (rentA !== rentB) {
      return rentA > rentB
        ? { canonical: pair.a, duplicate: pair.b, reason: pair.reason }
        : { canonical: pair.b, duplicate: pair.a, reason: pair.reason };
    }
  }

  const scoreA = scoreFixedExpense(pair.a, payments, bankTransactions);
  const scoreB = scoreFixedExpense(pair.b, payments, bankTransactions);
  const canonical = scoreA >= scoreB ? pair.a : pair.b;
  const duplicate = canonical.id === pair.a.id ? pair.b : pair.a;
  return { canonical, duplicate, reason: pair.reason };
}

function indexPaymentsByMonth(paymentList) {
  const map = new Map();
  for (const payment of paymentList) {
    const mk = monthKey(payment.date);
    if (!map.has(mk)) map.set(mk, []);
    map.get(mk).push(payment);
  }
  return map;
}

function chooseMonthPayment(group, bankTransactions) {
  const linked = group.filter((row) => isFixedExpensePaymentBankLinked(row, bankTransactions));
  if (linked.length === 1) return { keep: linked[0], drop: group.filter((row) => row.id !== linked[0].id) };
  if (linked.length > 1) {
    const manual = linked.find((row) => !isAutoGeneratedPayment(row));
    const keep = manual || linked[0];
    return { keep, drop: group.filter((row) => row.id !== keep.id) };
  }
  const manual = group.find((row) => !isAutoGeneratedPayment(row));
  if (manual) return { keep: manual, drop: group.filter((row) => row.id !== manual.id) };
  return { keep: group[0], drop: group.slice(1) };
}

function mergeDuplicateFixedExpenses(data) {
  const fixedExpenses = [...(data.fixedExpenses || [])];
  let payments = [...(data.fixedExpensePayments || [])];
  let bankTransactions = [...(data.bankTransactions || [])];
  let bankLedgerRules = [...(data.bankLedgerRules || [])];

  const pairs = findDuplicatePairs(fixedExpenses, payments, bankTransactions);
  const merges = pairs.map((pair) => pickCanonical(pair, payments, bankTransactions));

  const duplicateIds = new Set();
  const actions = [];

  for (const { canonical, duplicate, reason } of merges) {
    if (duplicateIds.has(duplicate.id) || duplicateIds.has(canonical.id)) continue;

    let reassigned = 0;
    let removed = 0;
    const removedPaymentIds = new Set();

    const duplicatePayments = payments.filter((row) => row.fixedExpenseId === duplicate.id);
    payments = payments.filter((row) => row.fixedExpenseId !== duplicate.id);

    const canonicalPayments = payments.filter((row) => row.fixedExpenseId === canonical.id);
    const combinedByMonth = indexPaymentsByMonth([
      ...canonicalPayments,
      ...duplicatePayments.map((row) => ({ ...row, fixedExpenseId: canonical.id, sourceExpenseId: duplicate.id })),
    ]);

    const nextCanonicalPayments = [];
    for (const [, group] of combinedByMonth) {
      const { keep, drop } = chooseMonthPayment(group, bankTransactions);
      nextCanonicalPayments.push({ ...keep, fixedExpenseId: canonical.id, sourceExpenseId: undefined });
      for (const row of drop) {
        removed += 1;
        removedPaymentIds.add(row.id);
      }
      if (keep.sourceExpenseId === duplicate.id) reassigned += 1;
    }

    payments = [
      ...payments.filter((row) => row.fixedExpenseId !== canonical.id),
      ...nextCanonicalPayments,
    ];

    bankTransactions = bankTransactions.map((tx) => {
      if (!removedPaymentIds.has(String(tx.linkedFixedExpensePaymentId || ""))) return tx;
      return { ...tx, linkedFixedExpensePaymentId: undefined };
    });

    bankLedgerRules = bankLedgerRules.map((rule) => {
      if (rule.kind !== "fixed" || rule.fixedExpenseId !== duplicate.id) return rule;
      return { ...rule, fixedExpenseId: canonical.id };
    });

    duplicateIds.add(duplicate.id);
    actions.push({
      reason,
      keep: { id: canonical.id, name: canonical.name, category: canonical.category, amount: canonical.amount },
      remove: { id: duplicate.id, name: duplicate.name, category: duplicate.category, amount: duplicate.amount },
      reassignedPayments: reassigned,
      removedPayments: removed,
    });
  }

  const nextFixedExpenses = fixedExpenses.filter((row) => !duplicateIds.has(row.id));

  const seenRuleKeys = new Set();
  bankLedgerRules = bankLedgerRules.filter((rule) => {
    if (rule.kind !== "fixed") return true;
    const key = `${rule.fixedExpenseId}:${rule.counterpartyKey || ""}:${rule.category || ""}`;
    if (seenRuleKeys.has(key)) return false;
    seenRuleKeys.add(key);
    return true;
  });

  const pruned = pruneSettledDuplicateFixedExpensePayments({
    fixedExpensePayments: payments,
    bankTransactions,
    fixedExpenses: nextFixedExpenses,
  });

  return {
    fixedExpenses: nextFixedExpenses,
    fixedExpensePayments: pruned.payments,
    bankTransactions,
    bankLedgerRules,
    actions,
    prunedPaymentIds: pruned.removedIds,
  };
}

const db = new DatabaseSync(dbPath);
const state = db.prepare("SELECT payload, version FROM erp_state WHERE id = 1").get();
const data = JSON.parse(String(state.payload));

const beforeCount = (data.fixedExpenses || []).length;
const result = mergeDuplicateFixedExpenses(data);

const summary = {
  dryRun,
  version: Number(state.version || 0) + (dryRun ? 0 : 1),
  beforeFixedExpenseCount: beforeCount,
  afterFixedExpenseCount: result.fixedExpenses.length,
  mergedCount: result.actions.length,
  prunedAutoPayments: result.prunedPaymentIds.length,
  actions: result.actions,
};

console.log(JSON.stringify(summary, null, 2));

if (dryRun || !result.actions.length) {
  process.exit(0);
}

const nextPayload = {
  ...data,
  fixedExpenses: result.fixedExpenses,
  fixedExpensePayments: result.fixedExpensePayments,
  bankTransactions: result.bankTransactions,
  bankLedgerRules: result.bankLedgerRules,
};

db.prepare("UPDATE erp_state SET payload = ?, version = ?, updated_at = ?, updated_by = ? WHERE id = 1").run(
  JSON.stringify(nextPayload),
  summary.version,
  new Date().toISOString(),
  "repair-merge-duplicate-fixed-expenses",
);
